func (s *Server) systemInterfaces() ([]model.SystemInterface, error) {
	ifaces, err := netutil.Interfaces()
	if err != nil {
		return nil, err
	}
	for i := range ifaces {
		ifaces[i].Gateway = netutil.GatewayFor(ifaces[i].Name, ifaces)
	}
	return ifaces, nil
}

// isDemo reports whether the active data dir was generated by `netdiag demo`.
func (s *Server) isDemo() bool {
	if s.cfg == nil {
		return false
	}
	return demo.Active(s.cfg.Storage.DataDir)
}

func (s *Server) handleSystemInfo(w http.ResponseWriter, r *http.Request) {
	hostname, _ := os.Hostname()
	ifaces, _ := s.systemInterfaces()
	info := model.SystemInfo{
		Demo:       s.isDemo(),
		Version:    s.version,
		Commit:     s.commit,
		BuildDate:  s.buildDate,
		GoVersion:  runtime.Version(),
		Hostname:   hostname,
		OS:         runtime.GOOS,
		Arch:       runtime.GOARCH,
		UptimeSecs: int64(time.Since(s.startedAt).Seconds()),
		StartedAt:  s.startedAt,
		DataDir:    s.cfg.Storage.DataDir,
		DBSize:     s.dbSize(),
		Interfaces: ifaces,
		Capabilities: map[string]bool{
			"active_arp":   discover.ARPAvailable(),
			"dhcp_probe":   discover.DHCPAvailable(),
			"passive_arp":  true,
			"icmp":         true,
			"snmp":         true,
			"alerts":       s.cfg.Alerts.Enabled,
			"auth":         s.cfg.Security.Auth,
			"monitor":      s.cfg.Monitor.Enabled,
			"vpn":          s.cfg.VPN.Enabled,
			"wifi_capture": wifi.Available(),
			"wifi":         s.cfg.WiFi.Enabled && s.cfg.WiFi.Interface != "",
		},
	}
	writeJSON(w, http.StatusOK, info)
}

func (s *Server) handleGetConfig(w http.ResponseWriter, r *http.Request) {
	if !s.requireAdmin(w, r) {
		return
	}
	cfg := *s.cfg
	if cfg.Scan.SNMPv3Auth != "" {
		cfg.Scan.SNMPv3Auth = maskedSecret
	}
	if cfg.Scan.SNMPv3Priv != "" {
		cfg.Scan.SNMPv3Priv = maskedSecret
	}
	if cfg.Security.MetricsToken != "" {
		cfg.Security.MetricsToken = maskedSecret
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"config": cfg,
		"path":   s.configPath,
	})
}

func (s *Server) handleUpdateConfig(w http.ResponseWriter, r *http.Request) {
	if !s.requireAdmin(w, r) {
		return
	}
	var incoming config.Config
	if err := decode(r, &incoming); err != nil {
		s.fail(w, r, http.StatusBadRequest, "configuración inválida: "+err.Error())
		return
	}
	// Preserve masked SNMPv3 secrets.
	if incoming.Scan.SNMPv3Auth == maskedSecret || incoming.Scan.SNMPv3Auth == "" {
		incoming.Scan.SNMPv3Auth = s.cfg.Scan.SNMPv3Auth
	}
	if incoming.Scan.SNMPv3Priv == maskedSecret || incoming.Scan.SNMPv3Priv == "" {
		incoming.Scan.SNMPv3Priv = s.cfg.Scan.SNMPv3Priv
	}
	if incoming.Security.MetricsToken == maskedSecret || incoming.Security.MetricsToken == "" {
		incoming.Security.MetricsToken = s.cfg.Security.MetricsToken
	}
	if err := incoming.Normalize(); err != nil {
		s.fail(w, r, http.StatusBadRequest, err.Error())
		return
	}
	path := s.configPath
	if path == "" {
		path = config.DefaultPath()
	}
	if err := incoming.Save(path); err != nil {
		s.fail(w, r, http.StatusInternalServerError, "no se pudo guardar la configuración: "+err.Error())
		return
	}
	if s.scanner != nil {
		if err := s.scanner.UpdateConfig(&incoming); err != nil {
			s.fail(w, r, http.StatusInternalServerError, "configuración guardada, pero no se pudo aplicar: "+err.Error())
			return
		}
	}
	s.SetConfig(&incoming)
	s.audit(r, "config.updated", path, nil)
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "path": path})
}

func (s *Server) handleAudit(w http.ResponseWriter, r *http.Request) {
	if !s.requireAdmin(w, r) {
		return
	}
	from, to := parseWindow(r, 7*24*time.Hour)
	f := model.AuditFilter{
		Actor:  queryString(r, "actor"),
		Action: queryString(r, "action"),
		Page:   queryInt(r, "page", 1),
		Limit:  queryInt(r, "limit", 100),
	}
	if queryString(r, "from") != "" {
		f.From = &from
	}
	if queryString(r, "to") != "" {
		f.To = &to
	}
	res, err := s.st.ListAudit(f)
	if err != nil {
		s.fail(w, r, http.StatusInternalServerError, err.Error())
		return
	}
	writeJSON(w, http.StatusOK, res)
}

func (s *Server) handleTopology(w http.ResponseWriter, r *http.Request) {
	siteID := queryInt64(r, "site_id")
	hosts, err := s.st.ListAllHostsForSite(siteID, 20000)
	if err != nil {
		s.fail(w, r, http.StatusInternalServerError, "no se pudo leer el inventario: "+err.Error())
		return
	}
	neighbors, err := s.st.AllNeighbors()
	if err != nil {
		neighbors = map[int64][]model.Neighbor{}
	}
	var networks []model.Network
	if siteID > 0 {
		networks, err = s.st.ListNetworksBySite(siteID)
	} else {
		networks, err = s.st.ListNetworks()
	}
	if err != nil {
		s.fail(w, r, http.StatusInternalServerError, err.Error())
		return
	}
	// Optional filter by network.
	if nid := queryInt64(r, "network_id"); nid > 0 {
		var filtered []model.Host
		for _, h := range hosts {
			if h.NetworkID == nid {
				filtered = append(filtered, h)
			}
		}
		var nets []model.Network
		for _, n := range networks {
			if n.ID == nid {
				nets = append(nets, n)
			}
		}
		hosts, networks = filtered, nets
	}
	graph := topology.Build(hosts, neighbors, networks)
	s.mergeEnvironmentTopology(r.Context(), &graph, hosts)
	s.ensureSelfInventory()
	writeJSON(w, http.StatusOK, graph)
}

// ensureSelfInventory registers the local machine in the inventory with the
// "self" and "excluded" tags. It stays visible to the operator but is never
// counted as a managed (billable) host.
func (s *Server) ensureSelfInventory() {
	ifaces, err := s.systemInterfaces()
	if err != nil {
		return
	}
	hostname, _ := os.Hostname()
	tags := []string{"self", "excluded"}
	for _, iface := range ifaces {
		if iface.Loopback || !iface.Up || iface.MAC == "" {
			continue
		}
		for _, addr := range iface.Addrs {
			if addr.Family != "ipv4" || !addr.Private {
				continue
			}
			h := &model.Host{
				SiteID:     1,
				IP:         addr.IP,
				MAC:        iface.MAC,
				Hostname:   hostname,
				DeviceType: model.DevWorkstation,
				Status:     model.StatusUp,
				Confidence: 100,
				Evidence:   []string{"equipo local"},
			}
			id, _, _, _, err := s.st.UpsertHost(h)
			if err == nil {
				_ = s.st.UpdateHostMeta(id, nil, &tags, nil)
			}
		}
	}
}

// mergeEnvironmentTopology adds the local machine, auto-detected private
// networks and their routers to the rendered graph. Existing nodes are reused
// by IP/CIDR so the same device never appears twice, and edges follow the real
// traced hop sequence.
func (s *Server) mergeEnvironmentTopology(ctx context.Context, graph *model.Graph, hosts []model.Host) {
	local := []string{}
	ifaces, err := s.systemInterfaces()
	if err == nil {
		for _, iface := range ifaces {
			if iface.Loopback || !iface.Up {
				continue
			}
			for _, a := range iface.Addrs {
				if a.Family == "ipv4" && a.Private {
					local = append(local, a.CIDR)
				}
			}
		}
	}
	detected := s.ensureNeighbors(ctx, local, neighborSeeds(hosts))

	byID := map[string]bool{}
	byIP := map[string]string{}
	byCIDR := map[string]string{}
	for _, n := range graph.Nodes {
		byID[n.ID] = true
		if n.IP == "" {
			continue
		}
		if strings.Contains(n.IP, "/") {
			if byCIDR[n.IP] == "" {
				byCIDR[n.IP] = n.ID
			}
			continue
		}
		if byIP[n.IP] == "" {
			byIP[n.IP] = n.ID
		}
	}

	addNode := func(id, kind, label, ip, cidr string, confidence int) string {
		if id == "" {
			return ""
		}
		if !byID[id] {
			byID[id] = true
			graph.Nodes = append(graph.Nodes, model.GraphNode{
				ID:         id,
				Kind:       kind,
				Label:      label,
				IP:         ip,
				Network:    cidr,
				DeviceType: model.DevRouter,
				Confidence: confidence,
			})
			graph.Stats.Nodes++
			graph.Stats.ByType[kind]++
		}
		if ip != "" && !strings.Contains(ip, "/") && byIP[ip] == "" {
			byIP[ip] = id
		}
		if cidr != "" && byCIDR[cidr] == "" {
			byCIDR[cidr] = id
		}
		return id
	}

	edgeKeys := map[string]bool{}
	for _, e := range graph.Edges {
		edgeKeys[e.Source+"->"+e.Target+"|"+e.Kind] = true
	}
	addEdge := func(from, to, kind, label string, confidence int) {
		if from == "" || to == "" || from == to {
			return
		}
		key := from + "->" + to + "|" + kind
		if edgeKeys[key] {
			return
		}
		edgeKeys[key] = true
		graph.Edges = append(graph.Edges, model.GraphEdge{
			ID:         key,
			Source:     from,
			Target:     to,
			Kind:       kind,
			Label:      label,
			Confidence: confidence,
		})
		graph.Stats.Edges++
	}
	connected := func(a, b string) bool {
		for _, e := range graph.Edges {
			if (e.Source == a && e.Target == b) || (e.Source == b && e.Target == a) {
				return true
			}
		}
		return false
	}

	// The scanner excludes its own addresses from discovery. Add the local
	// machine explicitly so the operator can see where NetDiag is running.
	hostname, _ := os.Hostname()
	for _, iface := range ifaces {
		if iface.Loopback || !iface.Up {
			continue
		}
		for _, addr := range iface.Addrs {
			if addr.Family != "ipv4" || !addr.Private {
				continue
			}
			selfID := "self:" + addr.IP
			label := "Este equipo"
			if hostname != "" {
				label += " · " + hostname
			} else if iface.Name != "" {
				label += " · " + iface.Name
			}
			if !byID[selfID] {
				byID[selfID] = true
				graph.Nodes = append(graph.Nodes, model.GraphNode{
					ID:         selfID,
					Kind:       "host",
					Label:      label,
					IP:         addr.IP,
					MAC:        iface.MAC,
					DeviceType: model.DevWorkstation,
					Status:     model.StatusUp,
					IsSelf:     true,
					Confidence: 100,
				})
				graph.Stats.Nodes++
				graph.Stats.ByType[string(model.DevWorkstation)]++
			}
			if byIP[addr.IP] == "" {
				byIP[addr.IP] = selfID
			}
			netID := byCIDR[maskedCIDR(addr.CIDR)]
			if netID == "" {
				netID = byIP[iface.Gateway]
			}
			if netID != "" {
				addEdge(netID, selfID, "local", "equipo local", 100)
			}
		}
	}

	for _, nw := range detected.Networks {
		netID := byCIDR[nw.CIDR]
		if netID == "" {
			netID = addNode("neighbor:"+nw.CIDR, "network", "Red vecina · "+nw.CIDR, nw.CIDR, nw.CIDR, nw.Confidence)
		}

		label := nw.RouterIP
		if nw.RouterHostname != "" {
			label = nw.RouterHostname
		}
		routerID := byIP[nw.RouterIP]
		if routerID == "" {
			routerID = addNode("neighbor-router:"+nw.RouterIP, "router", label, nw.RouterIP, nw.CIDR, nw.Confidence)
		}

		// Draw the path hop by hop: 192.168.0.1 -> 192.168.1.1.
		previous := ""
		for _, hop := range nw.Path {
			if hop == "" || hop == "*" || net.ParseIP(hop) == nil {
				continue
			}
			hopID := byIP[hop]
			if hopID == "" {
				hopID = addNode("neighbor-router:"+hop, "router", hop, hop, "", nw.Confidence)
			}
			if previous != "" {
				addEdge(previous, hopID, "traced", "traza", nw.Confidence)
			}
			previous = hopID
		}
		if previous != "" && previous != routerID {
			addEdge(previous, routerID, "traced", "traza", nw.Confidence)
		}
		if !connected(netID, routerID) {
			addEdge(netID, routerID, "gateway", nw.Evidence, nw.Confidence)
		}
	}

	graph.Stats.Isolated = countIsolated(graph)
	graph.Stats.Nodes = len(graph.Nodes)
	graph.Stats.Edges = len(graph.Edges)
}

func maskedCIDR(value string) string {
	p, err := netip.ParsePrefix(strings.TrimSpace(value))
	if err != nil || !p.Addr().Is4() {
		return value
	}
	return netip.PrefixFrom(p.Addr().Unmap(), p.Bits()).Masked().String()
}

func countIsolated(g *model.Graph) int {
	connected := map[string]bool{}
	for _, e := range g.Edges {
		connected[e.Source] = true
		connected[e.Target] = true
	}
	n := 0
	for _, node := range g.Nodes {
		if !connected[node.ID] {
			n++
		}
	}
	return n
}
